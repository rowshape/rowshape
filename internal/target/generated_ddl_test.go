package target

import (
	"strings"
	"testing"

	"github.com/rowshape/rowshape/internal/fixture"
)

func generatedFixture() *fixture.Fixture {
	return &fixture.Fixture{
		Tables: map[string]fixture.Table{
			"app.orders": {
				Rows: fixture.Fact[int64]{Value: 100},
				Columns: map[string]fixture.Column{
					"id":       {Type: "bigint", Generated: "identity", Identity: "by_default"},
					"subtotal": {Type: "numeric(12,2)"},
					"tax":      {Type: "numeric(12,2)"},
					"total": {Type: "numeric(12,2)", Nullable: true,
						Generated: "stored", GeneratedExpression: "(subtotal + tax)"},
				},
			},
		},
	}
}

// TestDDLRendersGeneratedColumns is the wrong-PASS regression, in both directions.
// A STORED generated column rebuilt as an ordinary one ACCEPTS an UPDATE that
// production rejects with `column "total" can only be updated to DEFAULT`; an
// identity column rebuilt as a plain NOT NULL one REJECTS an INSERT that omits it,
// which production accepts.
func TestDDLRendersGeneratedColumns(t *testing.T) {
	stmt := findStatement(t, DDL(generatedFixture()), "orders")
	for _, want := range []string{
		`GENERATED BY DEFAULT AS IDENTITY`,
		`GENERATED ALWAYS AS ((subtotal + tax)) STORED`,
	} {
		if !strings.Contains(stmt, want) {
			t.Errorf("missing %q in:\n%s", want, stmt)
		}
	}
}

// TestDDLIdentityAlwaysVsByDefault: an ALWAYS column REJECTS an explicit value in
// an INSERT unless the statement says OVERRIDING SYSTEM VALUE, so the two are not
// interchangeable.
func TestDDLIdentityAlwaysVsByDefault(t *testing.T) {
	f := generatedFixture()
	col := f.Tables["app.orders"].Columns["id"]
	col.Identity = "always"
	f.Tables["app.orders"].Columns["id"] = col

	stmt := findStatement(t, DDL(f), "orders")
	if !strings.Contains(stmt, "GENERATED ALWAYS AS IDENTITY") {
		t.Errorf("ALWAYS identity rendered as BY DEFAULT:\n%s", stmt)
	}
}

// TestDDLIdentityWithoutKindDefaultsToPermissive: a fixture written before the
// `identity` field says only `generated: identity`. BY DEFAULT is the safer
// reading, because it accepts explicit values and hydration supplies them.
func TestDDLIdentityWithoutKindDefaultsToPermissive(t *testing.T) {
	f := generatedFixture()
	col := f.Tables["app.orders"].Columns["id"]
	col.Identity = ""
	f.Tables["app.orders"].Columns["id"] = col

	stmt := findStatement(t, DDL(f), "orders")
	if !strings.Contains(stmt, "GENERATED BY DEFAULT AS IDENTITY") {
		t.Errorf("identity without a recorded kind must render BY DEFAULT:\n%s", stmt)
	}
}

// TestDDLOpaqueGenerationExpressionIsNotInvented: "opaque" is the placeholder
// privacy:strict leaves behind. An invented expression would compute values
// production never held.
func TestDDLOpaqueGenerationExpressionIsNotInvented(t *testing.T) {
	for _, expr := range []string{"", "opaque"} {
		f := generatedFixture()
		col := f.Tables["app.orders"].Columns["total"]
		col.GeneratedExpression = expr
		f.Tables["app.orders"].Columns["total"] = col

		stmt := findStatement(t, DDL(f), "orders")
		if strings.Contains(stmt, "GENERATED ALWAYS AS (") {
			t.Errorf("generation expression invented from %q:\n%s", expr, stmt)
		}
		// And it must be REPORTED, because the target is now more permissive than
		// production: it accepts an UPDATE production rejects.
		got := UnreproducibleGenerated(f)
		if len(got) != 1 || got[0] != "app.orders.total" {
			t.Errorf("unreproducible generated column not reported for %q: %v", expr, got)
		}
	}
}

// TestUnreproducibleGeneratedIsQuietWhenReproducible guards the other direction:
// a fully described generated column is not reported as a limitation.
func TestUnreproducibleGeneratedIsQuietWhenReproducible(t *testing.T) {
	if got := UnreproducibleGenerated(generatedFixture()); len(got) != 0 {
		t.Errorf("reproducible generated column reported as a limitation: %v", got)
	}
}

// TestIdentityResetsAdvanceTheSequence: hydration supplies explicit ids, which an
// identity sequence does not observe. Left at 1 while the table holds 1..N, the
// first INSERT that omits the column collides with the primary key — a wrong FAIL
// on the ordinary way to insert into an identity table.
func TestIdentityResetsAdvanceTheSequence(t *testing.T) {
	stmts := identityResets(generatedFixture())
	if len(stmts) != 1 {
		t.Fatalf("want one reset (for the identity column), got %v", stmts)
	}
	for _, want := range []string{"setval", "pg_get_serial_sequence", "MAX(\"id\")", "COALESCE"} {
		if !strings.Contains(stmts[0], want) {
			t.Errorf("missing %q: %s", want, stmts[0])
		}
	}
}

// TestIdentityResetsIgnoreOrdinaryColumns: a table with no identity column needs
// no sequence bookkeeping, and emitting one would fail on a NULL sequence name.
func TestIdentityResetsIgnoreOrdinaryColumns(t *testing.T) {
	f := &fixture.Fixture{
		Tables: map[string]fixture.Table{
			"app.plain": {
				Rows:    fixture.Fact[int64]{Value: 10},
				Columns: map[string]fixture.Column{"id": {Type: "bigint"}},
			},
		},
	}
	if got := identityResets(f); len(got) != 0 {
		t.Errorf("sequence reset emitted for a table with no identity column: %v", got)
	}
}

// TestVirtualGeneratedColumnIsNotReproduced: PostgreSQL 18 added VIRTUAL
// generated columns. Their syntax exists only on 18+, so emitting it would make a
// fixture pulled from an 18 source unhydratable on the 10–17 targets rowshape
// supports — the column becomes ordinary and is REPORTED instead.
//
// The branch matters even before 18 is claimed: without it a virtual column fell
// through to the ordinary-column path and its generation expression was recorded
// as a plain DEFAULT, which the target then emitted — so an UPDATE production
// rejects would have succeeded there.
func TestVirtualGeneratedColumnIsNotReproduced(t *testing.T) {
	f := generatedFixture()
	col := f.Tables["app.orders"].Columns["total"]
	col.Generated = "virtual"
	col.GeneratedExpression = "(subtotal + tax)"
	f.Tables["app.orders"].Columns["total"] = col

	if got := generatedClause(col); got != "" {
		t.Errorf("virtual column rendered a GENERATED clause %q; the syntax does not exist on 10-17", got)
	}
	if got := defaultClause(col); got != "" {
		t.Errorf("virtual column's generation expression leaked out as a DEFAULT: %q", got)
	}
	got := UnreproducibleGenerated(f)
	if len(got) != 1 || got[0] != "app.orders.total" {
		t.Errorf("virtual column not reported as unreproducible: %v", got)
	}
}
