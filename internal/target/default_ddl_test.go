package target

import (
	"strings"
	"testing"

	"github.com/rowshape/rowshape/internal/fixture"
)

func defaultFixture() *fixture.Fixture {
	return &fixture.Fixture{
		Tables: map[string]fixture.Table{
			"app.orders": {
				Rows: fixture.Fact[int64]{Value: 100},
				Columns: map[string]fixture.Column{
					"payload": {Type: "jsonb", Default: `'{}'::jsonb`},
					"status":  {Type: "text", Default: `'pending'::text`},
					"plain":   {Type: "bigint", Nullable: true},
					"id":      {Type: "bigint", Generated: "identity", Identity: "by_default"},
					"total":   {Type: "numeric(12,2)", Nullable: true, Generated: "stored", GeneratedExpression: "(a + b)"},
				},
			},
		},
	}
}

// TestDDLRendersColumnDefaults is the wrong-FAIL regression. A bare NOT NULL
// where production has NOT NULL DEFAULT made every migration that inserts or
// backfills without naming the column fail in the target and succeed in
// production — the most ordinary statement there is.
func TestDDLRendersColumnDefaults(t *testing.T) {
	stmt := findStatement(t, DDL(defaultFixture()), "orders")
	for _, want := range []string{`DEFAULT '{}'::jsonb`, `DEFAULT 'pending'::text`} {
		if !strings.Contains(stmt, want) {
			t.Errorf("missing %q:\n%s", want, stmt)
		}
	}
}

// TestDDLGeneratedColumnsGetNoDefault: DEFAULT is not legal alongside GENERATED,
// and `generated` already carries how the value arrives. An identity column's
// implicit nextval(...) must never surface as a default either — it would name a
// sequence the target does not have.
func TestDDLGeneratedColumnsGetNoDefault(t *testing.T) {
	f := defaultFixture()
	for _, name := range []string{"id", "total"} {
		col := f.Tables["app.orders"].Columns[name]
		col.Default = `nextval('app.orders_id_seq'::regclass)`
		f.Tables["app.orders"].Columns[name] = col
	}
	// Asserted on the clause itself rather than on the rendered line: "GENERATED BY
	// DEFAULT AS IDENTITY" contains the word DEFAULT, so a substring match on the
	// line reports a problem that is not there.
	for _, name := range []string{"id", "total"} {
		if got := defaultClause(f.Tables["app.orders"].Columns[name]); got != "" {
			t.Errorf("generated column %s carries a DEFAULT clause: %q", name, got)
		}
	}
	// And no sequence is invented for the nextval an identity column implies.
	for _, s := range DDL(f) {
		if strings.HasPrefix(s, "CREATE SEQUENCE") {
			t.Errorf("sequence created for a generated column's implicit default: %s", s)
		}
	}
}

// TestDDLCreatesSequencesNamedByDefaults: a serial column is an ordinary column
// with a nextval default PLUS an owned sequence, and the sequence is a separate
// object the fixture does not otherwise carry — so CREATE TABLE failed with
// `relation "app.events_id_seq" does not exist`.
func TestDDLCreatesSequencesNamedByDefaults(t *testing.T) {
	f := defaultFixture()
	col := f.Tables["app.orders"].Columns["plain"]
	col.Default = `nextval('app.orders_plain_seq'::regclass)`
	f.Tables["app.orders"].Columns["plain"] = col

	stmts := DDL(f)
	seqAt, tableAt := -1, -1
	for i, s := range stmts {
		if strings.HasPrefix(s, "CREATE SEQUENCE") && strings.Contains(s, "app.orders_plain_seq") && seqAt < 0 {
			seqAt = i
		}
		if strings.HasPrefix(s, "CREATE TABLE") && tableAt < 0 {
			tableAt = i
		}
	}
	if seqAt < 0 {
		t.Fatalf("sequence named by a default was not created:\n%s", strings.Join(stmts, "\n"))
	}
	if seqAt > tableAt {
		t.Errorf("CREATE SEQUENCE at %d must precede the table that defaults to it (%d)", seqAt, tableAt)
	}
	// IF NOT EXISTS, so two columns defaulting to one sequence do not collide.
	if !strings.Contains(stmts[seqAt], "IF NOT EXISTS") {
		t.Errorf("sequence creation is not idempotent: %s", stmts[seqAt])
	}
}

// TestNextvalSequenceIgnoresOtherDefaults: anything not recognized with certainty
// must yield nothing, so an unusual default fails loudly on its own terms rather
// than having a sequence invented for it.
func TestNextvalSequenceIgnoresOtherDefaults(t *testing.T) {
	for _, clause := range []string{"", " DEFAULT now()", " DEFAULT '{}'::jsonb", " DEFAULT nextval(", " DEFAULT nextval('')"} {
		if name, ok := nextvalSequence(clause); ok {
			t.Errorf("clause %q produced sequence %q", clause, name)
		}
	}
	if name, ok := nextvalSequence(` DEFAULT nextval('app.t_id_seq'::regclass)`); !ok || name != "app.t_id_seq" {
		t.Errorf("nextvalSequence = %q, %v; want app.t_id_seq, true", name, ok)
	}
}

// TestOpaqueDefaultIsNotInventedAndIsReported: "opaque" is the privacy:strict
// placeholder. Inventing a default would give the target one production does not
// have; leaving it off silently leaves the target REJECTING writes production
// accepts, which is the direction that turns a clean migration into a FAIL.
func TestOpaqueDefaultIsNotInventedAndIsReported(t *testing.T) {
	f := defaultFixture()
	col := f.Tables["app.orders"].Columns["payload"]
	col.Default = "opaque"
	f.Tables["app.orders"].Columns["payload"] = col

	if stmt := findStatement(t, DDL(f), "orders"); strings.Contains(stmt, "opaque") {
		t.Errorf("opaque default rendered:\n%s", stmt)
	}
	got := UnreproducibleDefaults(f)
	if len(got) != 1 || got[0] != "app.orders.payload" {
		t.Errorf("withheld default on a NOT NULL column not reported: %v", got)
	}
	// A NULLABLE column with a withheld default is not a problem: an insert that
	// omits it simply gets NULL, which the column allows.
	col.Nullable = true
	f.Tables["app.orders"].Columns["payload"] = col
	if got := UnreproducibleDefaults(f); len(got) != 0 {
		t.Errorf("nullable column with a withheld default reported: %v", got)
	}
}
