// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import sitemap from '@astrojs/sitemap';
import { unified } from '@astrojs/markdown-remark';
import { SITE, REPO } from './src/site.ts';
import { lastmodFor } from './src/lastmod.ts';
import remarkLinkFindingCodes from './src/plugins/remark-link-finding-codes.mjs';
import { findingsSidebar } from './src/findingsSidebar.mjs';
import rehypeScrollableTables from './src/plugins/rehype-scrollable-tables.mjs';

// The one place the stack is deliberately not Go (PRD §9). The Go decision was
// about the binary — single static artifact, no runtime, hydrate is CPU-bound —
// and none of that reasoning applies to a documentation site. Astro Starlight is
// purpose-built for docs plus a landing page, and it deploys onto the Cloudflare
// Pages standard the rest of this org already uses.
//
// https://astro.build/config
export default defineConfig({
	site: SITE,
	markdown: {
		// `markdown.remarkPlugins` is deprecated in Astro 7 — the supported path is
		// an explicit processor. Starlight reads `markdown.processor` and pushes its
		// own plugins onto it, so passing ours here composes with Starlight's rather
		// than replacing them.
		//
		// The plugin turns every mention of a finding code into a link to that
		// finding's page; see the plugin for why that is generated rather than
		// written by hand.
		//
		// The rehype plugin wraps each table in a focusable, named scroll region
		// so a keyboard user can scroll a wide one; see the plugin.
		processor: unified({
			remarkPlugins: [remarkLinkFindingCodes],
			rehypePlugins: [rehypeScrollableTables],
		}),
	},
	integrations: [
		// Declared explicitly so it can be configured. Starlight adds
		// `@astrojs/sitemap` on its own ONLY when the integration is not already
		// present, so listing it here replaces its default rather than duplicating
		// it — the sitemap was previously a bare list of 49 <loc> elements with no
		// <lastmod>, which tells a crawler nothing about what is worth re-fetching.
		sitemap({
			serialize(item) {
				// The date is the git commit date of the page's source, from
				// src/generated/lastmod.json. A route with no entry (added but not yet
				// committed) simply gets no <lastmod>: an absent date costs a hint, a
				// wrong one spends trust.
				const lastmod = lastmodFor(new URL(item.url).pathname);
				return lastmod ? { ...item, lastmod } : item;
			},
		}),
		starlight({
			title: 'rowshape',
			description:
				"The type-checker for PostgreSQL migrations: check a proposed schema change against your production data's shape and get a machine-readable verdict.",
			// Decouples the <title> tag from the page heading and de-duplicates the
			// homepage title. See the file for why both are needed.
			routeMiddleware: './src/starlightRouteData.ts',
			// Search loads its 94 KB UI on intent instead of on every page's idle
			// callback. See the component.
			components: { Search: './src/components/Search.astro' },
			// theme.css: the brand accent (#2E4A7D, the README badge colour) with
			// its contrast arithmetic. content.css: table regions, forced colors.
			customCss: ['./src/styles/theme.css', './src/styles/content.css'],
			// The mark beside the wordmark, not instead of it: the name is the
			// thing people search for. Two files because the light-mode square is
			// 2.3:1 against the dark header; the dark one is a lighter tint (3:1).
			logo: {
				light: './src/assets/mark-light.svg',
				dark: './src/assets/mark-dark.svg',
				replacesTitle: false,
			},
			// Long commands wrap instead of scrolling. A scrolling block at phone
			// width is a horizontal scroller, which Expressive Code makes focusable by
			// turning it into an unnamed role=region — two of those on a page fail
			// axe's landmark-unique, and a wrapped `docker run ...` is easier to read
			// than a half-hidden one anyway. Wrapped lines keep their indent.
			//
			// No per-language exceptions: Expressive Code only makes a scroller
			// focusable from JS, after an idle callback, so any block left to scroll
			// is one a keyboard cannot reach until then (or at all without JS). The
			// one aligned diagram (the MCP tool loop) is written to fit a phone.
			expressiveCode: {
				defaultProps: { wrap: true, preserveIndent: true },
			},
			social: [
				{ icon: 'github', label: 'GitHub', href: REPO },
			],
			// The social card. Starlight already emits twitter:card=summary_large_image
			// on every page, which without an image renders as a blank rectangle
			// wherever a link is shared — Slack, X, LinkedIn, Discord, and the link
			// previews inside the agent tooling this project is aimed at.
			//
			// One site-wide card rather than per-page generated ones: a per-page
			// image means rasterizing text at build time, which depends on the CI
			// runner's fonts and fails by silently rendering nothing. public/og.png is
			// generated by `npm run og` and committed, so the artifact is reviewable.
			//
			// og:image must be absolute — a relative one is ignored by every scraper.
			head: [
				{ tag: 'meta', attrs: { property: 'og:image', content: `${SITE}/og.png` } },
				{ tag: 'meta', attrs: { property: 'og:image:type', content: 'image/png' } },
				{ tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
				{ tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
				{
					tag: 'meta',
					attrs: {
						property: 'og:image:alt',
						content:
							'rowshape — the type-checker for PostgreSQL migrations. A terminal showing `rowshape validate` returning FAIL RS-LOCK-001: ACCESS EXCLUSIVE on users, ~4m.',
					},
				},
				{ tag: 'meta', attrs: { name: 'twitter:image', content: `${SITE}/og.png` } },
				// Starlight links /favicon.svg. These cover what does not read SVG:
				// iOS home screens, and the .ico that unfurlers and feed readers ask
				// for. Generated by `npm run icons`; see the script.
				{ tag: 'link', attrs: { rel: 'icon', href: '/favicon.ico', sizes: '32x32' } },
				{ tag: 'link', attrs: { rel: 'apple-touch-icon', href: '/apple-touch-icon.png' } },
			],
			editLink: {
				baseUrl: `${REPO}/edit/main/docs-site/`,
			},
			// The sections the docs are organized around. Content lands in P4-T4
			// (install, findings, privacy) and P4-T5 (agents/MCP, fixture spec); this
			// is the shape it lands into.
			sidebar: [
				// Six of the sections hold a single page, which rendered as a group
				// repeating its own name ("Install > Install"). Those pages are slug
				// items in two groups named for the reader's question instead; URLs
				// are unchanged because sidebar placement never moves a file.
				{
					label: 'Start here',
					items: [{ slug: 'install' }, { slug: 'quickstart' }, { slug: 'faq' }],
				},
				// Task-shaped pages (CI) that cut across the reference, rather than
				// describing one command.
				{ label: 'Guides', items: [{ autogenerate: { directory: 'guides' } }] },
				// Everything that runs rowshape from somewhere else: CI and agents. The
				// Action page lives under /reference/ (its URL is linked from READMEs
				// and the Marketplace), so it is a slug item here rather than a moved
				// file, and gencli marks it hidden so it does not also appear under
				// CLI reference — it is not a command.
				{
					label: 'Integrations',
					items: [
						{ slug: 'reference/github-action', label: 'GitHub Action' },
						{ autogenerate: { directory: 'agent' } },
					],
				},
				// Generated from the cobra tree by `go run ./tools/gencli`, with a
				// staleness test, so the reference cannot drift from the binary.
				{ label: 'CLI reference', items: [{ autogenerate: { directory: 'reference' } }] },
				// Grouped by namespace and labelled by code; see the helper for why.
				{ label: 'Findings', items: findingsSidebar() },
				// What leaves the machine, what the tool can and cannot know (the docs
				// promised to say fixture fidelity has limits), and the published
				// format a fixture follows.
				{
					label: 'Data & trust',
					items: [{ slug: 'privacy' }, { slug: 'fidelity' }, { slug: 'spec' }],
				},
			],
		}),
	],
});
